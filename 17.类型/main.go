// go 类型记录
package main

import (
	"fmt"
	"log"
)

// go是以个静态类型编程语言，所有的类型都是再编译时候就确定了
// 运行时直接使用，不会像js，python这种动态类型语句
// 本节主要是概念性的类容，类型也没有可写的语法

// 静态强类型
// 所谓静态，就是类型在编译期就确定了，之后的程序运行的生命周期都不会变
// 但是go中存在反射机制，使用反射可以破坏这个特性，这是后话了

func main() {
	// 例如：我声明一个变量a 类型是int
	var a int = 10

	// 上面的变量a的类型是编译器确定的，一旦确定后续就不会发生变化
	// 动态语言就不行
	// 强类型则指的是在程序中执行严格的类型检查，如果出现类型不匹配的情况时，
	// 会立即告诉程序员不应该这么做，而不是像动态语言一样去尝试推断可能的结果。
	// 所以下面的代码无法通过编译，因为两者类型不同，无法进行运算。
	// 错误: cannot use "刻晴" (untyped string constant)
	// as int value in assignmentcompilerIncompatibleAssign
	// a = "刻晴"
	fmt.Println(a)

	// 类型后置
	// 这是在go中一个特点，类型是在变量的后面
	// TypeSript和Go一样也是这样
	// 由于在学习Go之前就解除了TS所以对于这种写法我不陌生
	// 很多初次接触这种语法格式的开发者，觉得反人类
	// 但其实这是先入为主的思维误导了
	// 类型后置反而更加清晰，这是一种思维方式
	// 描述一个事物
	// 在java c++ 这些传统编程语言中是这样的
	// 一个某某类型的事务A: String A
	// 但是在go中是这样的
	// 事务A是某某类型：var A string
	// 不能说谁更加优秀，认为谁好是主观判断，别在意

	// 类型声明
	// go声明类型直接使用type关键字
	type myint int     // 这就是声明了一个自定义类型底层是int
	type fn func()     // 声明了一个函数类型
	type myint8 = int8 // 这是给int8增加一个别名

	// 类型转换
	// go中没有隐式转换和装箱拆箱之类的
	// 只有显式的类型转换
	var a1 = 10
	var b1 int64 = 13
	if b1 > int64(a1) {
		log.Println("a1没有b1大")
	}

	// 类型断言
	// 这是一个很特殊的操作
	// 只有空接口才能进行类型断崖
	var n any = 10
	v2, ok := n.(int)
	if ok {
		log.Printf("断言成功:%d", v2)
	}
}
